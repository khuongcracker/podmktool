//      Cái đổi theo ngôn ngữ là NGÔN NGỮ ĐẦU RA mà ta yêu cầu model trả về
//      (tên sản phẩm, mô tả, gợi ý bối cảnh... hiện cho user đọc).
//      Xem `outputLanguageLine()` bên dưới.

const LS_KEY = 'ui_lang'
export const LANGS = [
  { code: 'vi', flag: '🇻🇳', label: 'Tiếng Việt' },
  { code: 'en', flag: '🇬🇧', label: 'English' },
]

let lang = 'vi'
try {
  const saved = localStorage.getItem(LS_KEY)
  if (LANGS.some((l) => l.code === saved)) lang = saved
} catch (_) {}

const subs = new Set()
export const getLang = () => lang
export function setLang(next) {
  if (!LANGS.some((l) => l.code === next)) return
  lang = next
  try { localStorage.setItem(LS_KEY, next) } catch (_) {}
  subs.forEach((fn) => fn(next))
}
export function subscribeLang(fn) {
  subs.add(fn)
  return () => subs.delete(fn)
}

